import sys
import json
from pathlib import Path

sys.path.append(str(Path(__file__).resolve().parent.parent))

import numpy as np
import torch
import torch.nn as nn
from sklearn.metrics import accuracy_score, precision_score, recall_score, f1_score

from preprocessing.preprocess import preprocess_image


BASE_DIR = Path(__file__).resolve().parent.parent
DATASET_DIR = BASE_DIR / "dataset"
MODEL_DIR = BASE_DIR / "saved_models"
THRESHOLD_FILE = BASE_DIR / "inference" / "thresholds.json"

CATEGORIES = [
    "bottle", "cable", "capsule", "carpet", "grid",
    "hazelnut", "leather", "metal_nut", "pill", "screw",
    "tile", "toothbrush", "transistor", "wood", "zipper"
]

IMAGE_SIZE = (224, 224)


class ConvAutoencoder(nn.Module):
    def __init__(self):
        super().__init__()

        self.encoder = nn.Sequential(
            nn.Conv2d(3, 32, 3, stride=2, padding=1),
            nn.BatchNorm2d(32),
            nn.ReLU(inplace=True),

            nn.Conv2d(32, 64, 3, stride=2, padding=1),
            nn.BatchNorm2d(64),
            nn.ReLU(inplace=True),

            nn.Conv2d(64, 128, 3, stride=2, padding=1),
            nn.BatchNorm2d(128),
            nn.ReLU(inplace=True),

            nn.Conv2d(128, 256, 3, stride=2, padding=1),
            nn.BatchNorm2d(256),
            nn.ReLU(inplace=True),
        )

        self.decoder = nn.Sequential(
            nn.ConvTranspose2d(
                256, 128, 3, stride=2, padding=1, output_padding=1
            ),
            nn.BatchNorm2d(128),
            nn.ReLU(inplace=True),

            nn.ConvTranspose2d(
                128, 64, 3, stride=2, padding=1, output_padding=1
            ),
            nn.BatchNorm2d(64),
            nn.ReLU(inplace=True),

            nn.ConvTranspose2d(
                64, 32, 3, stride=2, padding=1, output_padding=1
            ),
            nn.BatchNorm2d(32),
            nn.ReLU(inplace=True),

            nn.ConvTranspose2d(
                32, 3, 3, stride=2, padding=1, output_padding=1
            ),
            nn.Sigmoid(),
        )

    def forward(self, x):
        return self.decoder(self.encoder(x))


def load_thresholds():
    if not THRESHOLD_FILE.exists():
        raise FileNotFoundError(
            f"Threshold file not found: {THRESHOLD_FILE}"
        )

    with open(THRESHOLD_FILE, "r", encoding="utf-8") as f:
        thresholds = json.load(f)

    missing = [c for c in CATEGORIES if c not in thresholds]

    if missing:
        raise ValueError(
            f"Missing thresholds for: {', '.join(missing)}"
        )

    return thresholds


def load_model(category):
    model_path = MODEL_DIR / f"{category}_autoencoder.pth"

    if not model_path.exists():
        raise FileNotFoundError(f"Model not found: {model_path}")

    model = ConvAutoencoder()

    checkpoint = torch.load(model_path, map_location="cpu")

    if isinstance(checkpoint, dict) and "model_state_dict" in checkpoint:
        checkpoint = checkpoint["model_state_dict"]

    model.load_state_dict(checkpoint)
    model.eval()

    return model


def image_to_tensor(image_path):
    normalized, _ = preprocess_image(image_path)

    if normalized.shape != (224, 224, 3):
        raise ValueError(
            f"Unexpected preprocessed shape: {normalized.shape}"
        )

    tensor = np.transpose(normalized, (2, 0, 1))
    return torch.from_numpy(tensor).float().unsqueeze(0)


@torch.no_grad()
def reconstruction_error(model, image_path):
    tensor = image_to_tensor(image_path)
    reconstructed = model(tensor)

    return float(
        torch.mean((tensor - reconstructed) ** 2).item()
    )


def collect_images(category):
    category_dir = DATASET_DIR / category
    test_dir = category_dir / "test"

    good_dir = test_dir / "good"
    good_images = sorted(good_dir.glob("*"))

    defective_images = []

    if test_dir.exists():
        for defect_dir in sorted(test_dir.iterdir()):
            if defect_dir.is_dir() and defect_dir.name != "good":
                defective_images.extend(
                    sorted(defect_dir.glob("*"))
                )

    return good_images, defective_images


def evaluate_category(category, thresholds):
    print()
    print("=" * 70)
    print(f"EVALUATING: {category.upper()}")
    print("=" * 70)

    model = load_model(category)

    # IMPORTANT:
    # Use the threshold generated by generate_thresholds.py.
    threshold = float(
        thresholds[category]["threshold"]
    )

    good_images, defective_images = collect_images(category)

    paths = good_images + defective_images
    labels = (
        [0] * len(good_images)
        + [1] * len(defective_images)
    )

    errors = []
    valid_labels = []

    for i, image_path in enumerate(paths):
        try:
            error = reconstruction_error(
                model,
                image_path
            )

            errors.append(error)
            valid_labels.append(labels[i])

        except Exception as e:
            print(
                f"Skipped {image_path.name}: {e}"
            )

    if not errors:
        print("No valid test images.")
        return

    predictions = [
        1 if error > threshold else 0
        for error in errors
    ]

    accuracy = accuracy_score(
        valid_labels,
        predictions
    )

    precision = precision_score(
        valid_labels,
        predictions,
        zero_division=0
    )

    recall = recall_score(
        valid_labels,
        predictions,
        zero_division=0
    )

    f1 = f1_score(
        valid_labels,
        predictions,
        zero_division=0
    )

    print(f"THRESHOLD : {threshold:.8f}")
    print(f"Accuracy  : {accuracy:.4f}")
    print(f"Precision : {precision:.4f}")
    print(f"Recall    : {recall:.4f}")
    print(f"F1 Score  : {f1:.4f}")
    print(f"Good      : {len(good_images)}")
    print(f"Defective : {len(defective_images)}")


def main():
    thresholds = load_thresholds()

    print()
    print("AUTOENCODER EVALUATION")
    print("=" * 90)
    print("Using thresholds.json generated by generate_thresholds.py")
    print("Preprocessing: resize -> RGB -> bilateral denoise -> CLAHE -> normalize")
    print("Input size: (224, 224)")
    print("=" * 90)

    for category in CATEGORIES:
        try:
            evaluate_category(
                category,
                thresholds
            )
        except Exception as e:
            print(
                f"{category.upper():12s} | ERROR: {e}"
            )

    print()
    print("=" * 90)
    print("Evaluation completed for all 15 categories.")
    print("=" * 90)


if __name__ == "__main__":
    main()
